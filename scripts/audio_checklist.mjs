// Prints (and writes AUDIO_ASSET_CHECKLIST.md) which narration files exist on disk.
//   node scripts/audio_checklist.mjs
// Internal tool only: there is no public page for it.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "frontend/src/data/audioManifest.json"), "utf8"));
const audioDir = join(root, "frontend/public/audio");
const EXT = ["wav", "mp3", "m4a", "ogg"];

const statusOf = (file) => {
  for (const e of EXT) if (existsSync(join(audioDir, `${file}.${e}`))) return { label: "Uploaded", detail: `${file}.${e}` };
  if (existsSync(join(audioDir, `${file}.placeholder.mp3`))) return { label: "Placeholder (AI voice)", detail: `${file}.placeholder.mp3` };
  return { label: "MISSING", detail: "" };
};

const titles = { root: "Main", level1: "Level 1: Origin Space", level2: "Level 2: Builder's Arena", level3: "Level 3: Mind Dungeon", level4: "Level 4: Growth Kingdom" };
const counts = { Uploaded: 0, "Placeholder (AI voice)": 0, MISSING: 0 };
let md = "# AUDIO ASSET CHECKLIST\n\nGenerated by `node scripts/audio_checklist.mjs`. Copy your recordings to the paths below (inside `frontend/public/`).\n`.wav` is preferred; `.mp3 .m4a .ogg` also work. Your file always beats the AI placeholder.\n";
for (const [group, title] of Object.entries(titles)) {
  md += `\n## ${title}\n\n| Audio file | Expected location | Purpose | Status |\n|---|---|---|---|\n`;
  for (const m of manifest.filter((x) => x.group === group)) {
    const s = statusOf(m.file);
    counts[s.label] += 1;
    md += `| \`${m.file}.wav\` | \`frontend/public/audio/${m.file}.wav\` | ${m.purpose} | ${s.label} |\n`;
  }
}
md += `\n**Totals:** ${counts.Uploaded} uploaded, ${counts["Placeholder (AI voice)"]} placeholder, ${counts.MISSING} missing (of ${manifest.length}).\n`;
writeFileSync(join(root, "AUDIO_ASSET_CHECKLIST.md"), md);
console.log(md);
